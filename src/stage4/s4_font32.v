module s4_font32 #(parameter PIPELINE_PIXELS=0)(input clk,input [13:0] address,input [4:0] pixel_column,output reg [31:0] data,output pixel_ink,pixel_halo);
wire ascii_char=address[13:5]<95;
wire [14:0] expanded={address[13:5],6'b0}-15'd3040+{9'b0,address[4:0],1'b0};
wire [13:0] word_address=ascii_char?address:expanded[13:0];
wire [31:0] words[0:6];reg [6:0] bank_select;reg ascii_mode;
always @(posedge clk)begin bank_select<=7'b1<<word_address[13:11];ascii_mode<=ascii_char;end
wire [31:0] selected_words=({32{bank_select[0]}}&words[0])|({32{bank_select[1]}}&words[1])|
 ({32{bank_select[2]}}&words[2])|({32{bank_select[3]}}&words[3])|({32{bank_select[4]}}&words[4])|
 ({32{bank_select[5]}}&words[5])|({32{bank_select[6]}}&words[6]);
always @*data=ascii_mode?{selected_words[15:0],16'b0}:{selected_words[15:0],selected_words[31:16]};
reg [31:0] column_mask,halo_mask;
wire [31:0] next_column=32'h80000000>>pixel_column;
always @(posedge clk)begin column_mask<=next_column;halo_mask<=(next_column<<1)|(next_column>>1);end
wire [6:0] ink_banks,halo_banks;genvar pixel_bank;
generate for(pixel_bank=0;pixel_bank<7;pixel_bank=pixel_bank+1)begin:pixel_select
 assign ink_banks[pixel_bank]=bank_select[pixel_bank]&&
  ((|(words[pixel_bank][15:0]&column_mask[31:16]))||(!ascii_mode&&(|(words[pixel_bank][31:16]&column_mask[15:0]))));
 assign halo_banks[pixel_bank]=bank_select[pixel_bank]&&
  ((|(words[pixel_bank][15:0]&halo_mask[31:16]))||(!ascii_mode&&(|(words[pixel_bank][31:16]&halo_mask[15:0]))));
end endgenerate
generate if(PIPELINE_PIXELS)begin:registered_pixels
 // 字库各分组先独立寄存，分离查表、列选择和最终合成的时序路径。
 reg [6:0] ink_q,halo_q;
 always @(posedge clk)begin ink_q<=ink_banks;halo_q<=halo_banks;end
 assign pixel_ink=|ink_q;assign pixel_halo=|halo_q;
end else begin:original_pixels
 assign pixel_ink=|ink_banks;assign pixel_halo=|halo_banks;
end endgenerate
